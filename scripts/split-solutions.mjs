#!/usr/bin/env node
/* ============================================================
   SCRIPTS/SPLIT-SOLUTIONS · per-chapter bundles of solution files
   ------------------------------------------------------------
   Part of the v14 performance work (see CHANGELOG-v14.md).

   Input : data/solutions.js        (the full bundle generated by
                                     scripts/build-solutions.mjs —
                                     still the source of truth and
                                     still used by the Node test
                                     suite, e.g. test_righe_v12.mjs)
   Output: data/solutions/chNN.js   (one small ES module per chapter,
                                     with only that chapter's records
                                     and support files)

   Why: the browser used to download the whole ~7.7 MB bundle on the
   first visit, right on the LCP critical chain. With the split,
   engine/solutions-db.js imports ONLY the chapter of the exercise
   being opened (ch. 2 is ~2 KB; the heavy image/data chapters load
   only when one of their exercises is opened). data/solutions.js
   stays in the repo as the build input and for the Node tests —
   it is never fetched by the browser anymore.

   Run it after regenerating data/solutions.js:
       node scripts/split-solutions.mjs
   ============================================================ */
import { writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'data', 'solutions');

const { SOLUTIONS_VERSION, CHAPTER_FILES, SOLUTIONS } = await import(
  join(root, 'data', 'solutions.js')
);
/* (absolute specifier: keeps the script runnable from any cwd) */

mkdirSync(outDir, { recursive: true });

/* chapters that own records and/or support files */
const chapters = [...new Set([
  ...Object.values(SOLUTIONS).map(r => r.ch),
  ...Object.keys(CHAPTER_FILES).map(Number),
])].sort((a, b) => a - b);

/* wipe stale chapter files from previous runs (keeps the dir in sync
   with the source bundle: chapters can disappear on a rebuild) */
for (const f of readdirSync(outDir)) {
  if (/^ch\d+\.js$/.test(f)) {
    console.log('  remove stale', f);
    rmSync(join(outDir, f));
  }
}

let total = 0;
for (const n of chapters) {
  const recs = {};
  for (const [id, rec] of Object.entries(SOLUTIONS)) {
    if (rec.ch === n) recs[id] = rec;
  }
  const chFiles = { [String(n)]: CHAPTER_FILES[n] || {} };
  const body =
`/* Generated by scripts/split-solutions.mjs — DO NOT edit by hand.
   Chapter ${n} bundle, split from data/solutions.js (v${SOLUTIONS_VERSION}):
   only the solution records and the support files of chapter ${n}.
   Loaded on demand by engine/solutions-db.js (v14 lazy per-chapter
   loading: the browser never downloads the whole 7.7 MB bundle). */
export const SOLUTIONS_VERSION = ${SOLUTIONS_VERSION};
export const CHAPTER_FILES = ${JSON.stringify(chFiles)};
export const SOLUTIONS = ${JSON.stringify(recs)};
`;
  const file = join(outDir, `ch${n}.js`);
  writeFileSync(file, body);
  const kb = (Buffer.byteLength(body) / 1024).toFixed(1);
  console.log(`  ch${n}.js  ${String(Object.keys(recs).length).padStart(3)} exercises  ${kb} KB`);
  total += Buffer.byteLength(body);
}
console.log(`OK · ${chapters.length} chapter bundles written to data/solutions/ (${(total / 1024).toFixed(0)} KB total, source bundle unchanged)`);
