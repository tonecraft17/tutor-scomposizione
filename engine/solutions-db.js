/* ============================================================
   ENGINE/SOLUTIONS-DB · local database of solution files
   ------------------------------------------------------------
   The official solutions (Python Crash Course, 3rd ed.) live in a
   browser IndexedDB database. On first use of a chapter, that
   chapter's bundle — data/solutions/chNN.js, generated by
   scripts/split-solutions.mjs — is downloaded and seeded.

   - LOCAL-FIRST: no network beyond the static chapter bundles,
     no account; each chapter is seeded only once (or whenever
     SOLUTIONS_INDEX_VERSION changes);
   - ===== CHANGED v14 · LAZY PER-CHAPTER LOADING ===== the whole
     ~7.7 MB bundle used to be downloaded on the first visit, right
     on the LCP critical chain (Lighthouse: 1.65 MB transferred,
     LCP 17.6 s). Now the browser fetches ONLY the chapter of the
     exercise being opened (ch. 2 ≈ 2 KB; the heavy image chapters
     10/12–14/16 load only when one of their exercises is opened);
   - data/solutions-index.js (lightweight, static import) exposes
     the metadata (mode, entry, file names) for the UI and lets the
     app answer "does this exercise have support files?" without
     touching the database;
   - if IndexedDB is unavailable (private mode etc.), there is a
     transparent fallback to the in-memory chapter bundles.

   Spoiler policy: the solution code is NEVER shown in the UI;
   it is used only by the runtime to provide the correct output
   of multi-file exercises.
   ============================================================ */
import { SOLUTIONS_INDEX, SOLUTIONS_INDEX_VERSION } from '../data/solutions-index.js?v=16.2'; // ===== CHANGED v16.1 · versioned specifier (stale-ServiceWorker fix, see app.js) =====
import { SOLUTIONS as CFG } from '../config.js?v=16.2';

let db = null;                      // IDBDatabase
const cache = new Map();            // id -> merged solution (or null)
const chapterMem = new Map();       // ch -> imported bundle (fallback: no IndexedDB)
const chapterBusy = new Map();      // ch -> Promise (import + seed in progress)
let initPromise = null;
let seedInfo = { done: false, count: 0, reseeded: false, fallback: false };

