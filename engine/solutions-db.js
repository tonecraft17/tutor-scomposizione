/* ---------- small promise layer over IndexedDB ---------- */
function idbOpen() {
  return new Promise((res, rej) => {
    if (!('indexedDB' in self)) { rej(new Error('IndexedDB not available')); return; }
    const req = indexedDB.open(CFG.idbName, CFG.idbVersion);
    req.onupgradeneeded = () => {
      const d = req.result;
      if (!d.objectStoreNames.contains('meta')) d.createObjectStore('meta');
      if (!d.objectStoreNames.contains('chapters')) d.createObjectStore('chapters');
      if (!d.objectStoreNames.contains('solutions')) d.createObjectStore('solutions');
    };
    req.onsuccess = () => res(req.result);
    req.onerror = () => rej(req.error || new Error('DB open failed'));
    req.onblocked = () => rej(new Error('DB blocked by another tab'));
  });
}
function idbGet(store, key) {
  return new Promise((res, rej) => {
    const tx = db.transaction(store, 'readonly');
    const r = tx.objectStore(store).get(key);
    r.onsuccess = () => res(r.result ?? null);
    r.onerror = () => rej(r.error);
  });
}
function txDone(tx) {
  return new Promise((res, rej) => { tx.oncomplete = () => res(); tx.onerror = () => rej(tx.error); tx.onabort = () => rej(tx.error); });
}

/* ---------- per-chapter seed ---------- */

/** Notifies the UI that a chapter bundle is being downloaded for the
 *  first time (app.js turns this into a discreet toast). */
function notifyChapterDownload(n) {
  try { document.dispatchEvent(new CustomEvent('soldb:chapter', { detail: { ch: n } })); } catch (e) { /* no DOM (Node tests) */ }
}

/** Writes one chapter's records + support files + seed marker. */
async function seedChapter(bundle, n) {
  const tx = db.transaction(['meta', 'chapters', 'solutions'], 'readwrite');
  const osSol = tx.objectStore('solutions');
  for (const [id, rec] of Object.entries(bundle.SOLUTIONS)) {
    osSol.put({ id, ch: rec.ch, entry: rec.entry, mode: rec.mode, reason: rec.reason || null, files: rec.files }, id);
  }
  tx.objectStore('chapters').put({ id: 'ch' + n, n, files: bundle.CHAPTER_FILES[String(n)] || {} }, 'ch' + n);
  tx.objectStore('meta').put({ indexVersion: SOLUTIONS_INDEX_VERSION, seededAt: new Date().toISOString() }, 'ch' + n);
  await txDone(tx);
}

/**
 * Makes sure chapter `n` is available (IndexedDB, or in memory when
 * IndexedDB is unavailable). Idempotent, one in-flight promise per
 * chapter. Returns the number of seeded records (0 if already seeded).
 */
function ensureChapter(n) {
  if (chapterMem.has(n)) return Promise.resolve(0);            // memory fallback already loaded
  if (chapterBusy.has(n)) return chapterBusy.get(n);           // already in progress
  const p = (async () => {
    if (db) {
      const meta = await idbGet('meta', 'ch' + n);
      if (meta && meta.indexVersion === SOLUTIONS_INDEX_VERSION) return 0;   // already seeded
    }
    const loader = CHAPTER_BUNDLES[n];
    if (!loader) return 0;                                      // chapter without solutions
    notifyChapterDownload(n);
    const bundle = await loader();
    if (db) {
      try { await seedChapter(bundle, n); }
      catch (e) { chapterMem.set(n, bundle); }                  // quota/write failure → in-memory fallback
    } else {
      /* no IndexedDB: transparent in-memory fallback for this chapter */
      chapterMem.set(n, bundle);
    }
    return Object.keys(bundle.SOLUTIONS).length;
  })();
  chapterBusy.set(n, p);                                        // a chapter is loaded once per session…
  p.catch(() => chapterBusy.delete(n));                         // …unless the download failed: allow a retry
  return p;
}

/* ---------- public API ---------- */

/**
 * Initializes the database. ===== CHANGED v14 ===== cheap: opens
 * IndexedDB and migrates a v13 bulk seed if present — it does NOT
 * download anything. Chapter bundles arrive on demand with
 * getSolution()/getSolutionRaw(). Idempotent.
 */
export function init() {
  if (initPromise) return initPromise;
  initPromise = (async () => {
    try {
      db = await idbOpen();
      /* migration: a v13-style bulk seed (meta key 'seed') already
         holds EVERY chapter's records with this same index version —
         mark the per-chapter markers so nothing is re-downloaded. */
      const legacy = await idbGet('meta', 'seed');
      if (legacy) {
        if (legacy.indexVersion === SOLUTIONS_INDEX_VERSION) {
          const tx = db.transaction('meta', 'readwrite');
          for (const n of Object.keys(CHAPTER_BUNDLES)) {
            tx.objectStore('meta').put({ indexVersion: SOLUTIONS_INDEX_VERSION, seededAt: legacy.seededAt, fromLegacy: true }, 'ch' + Number(n));
          }
          tx.objectStore('meta').delete('seed');
          await txDone(tx);
        } else {
          /* stale bulk seed (older index): clear everything, chapters
             will re-seed lazily from the fresh bundles */
          const tx = db.transaction(['meta', 'chapters', 'solutions'], 'readwrite');
          tx.objectStore('meta').clear();
          tx.objectStore('chapters').clear();
          tx.objectStore('solutions').clear();
          await txDone(tx);
          cache.clear();
          chapterBusy.clear();
        }
      }
      seedInfo = { done: true, count: Object.keys(SOLUTIONS_INDEX).length, reseeded: false, fallback: false };
    } catch (e) {
      /* no IndexedDB (private mode…): everything is served from the
         in-memory chapter bundles, downloaded on demand */
      db = null;
      seedInfo = { done: true, count: Object.keys(SOLUTIONS_INDEX).length, reseeded: false, fallback: true };
    }
    return seedInfo;
  })();
  return initPromise;
}

/** Synchronous metadata (from the lightweight index): null if the exercise has no solution. */
export function indexFor(id) { return SOLUTIONS_INDEX[id] || null; }

/** Number of exercises with a solution in the database. */
export function indexCount() { return Object.keys(SOLUTIONS_INDEX).length; }

/** ===== v12 · all ids with a solution (to find chains of exercises
 *  that share the same program). ===== */
export function indexIds() { return Object.keys(SOLUTIONS_INDEX); }

/** Seed status (for statusbar/diagnostics). */
export function seedStatus() { return Object.assign({}, seedInfo); }

/**
 * Returns the exercise ready for execution:
 *   { id, ch, entry, mode ('run'|'pytest'|'none'), reason, files }
 * `files` = the chapter's support files ⊎ the exercise's own files,
 * with relative paths; values are UTF-8 strings or
 * { b64 } for binary files (images…). null if not present.
 * ===== CHANGED v14 ===== on the first call for a chapter this also
 * downloads + seeds that chapter's bundle (few KB; the heavy chapters
 * only when one of their exercises is opened).
 */
export async function getSolution(id) {
  if (cache.has(id)) return cache.get(id);
  const idx = SOLUTIONS_INDEX[id];
  if (!idx) { cache.set(id, null); return null; }
  await init();
  await ensureChapter(idx.ch);
  let rec = null, chFiles = {};
  if (db) {
    rec = await idbGet('solutions', id);
    if (rec) {
      const chRec = await idbGet('chapters', 'ch' + rec.ch);
      if (chRec) chFiles = chRec.files || {};
    }
  } else if (chapterMem.has(idx.ch)) {
    const bundle = chapterMem.get(idx.ch);
    rec = bundle.SOLUTIONS[id] || null;
    chFiles = bundle.CHAPTER_FILES[idx.ch] || {};
  }
  if (!rec) { cache.set(id, null); return null; }
  const files = Object.assign({}, chFiles, rec.files || {});
  const sol = { id, ch: idx.ch, entry: rec.entry, mode: rec.mode, reason: rec.reason || null, files };
  cache.set(id, sol);
  return sol;
}

/** ===== v12 · RAW solution record: ONLY the exercise's own
 *  files (without the chapter's support files), to tell which files
 *  the exercise actually writes/modifies («Lines» panel). ===== */
export async function getSolutionRaw(id) {
  const idx = SOLUTIONS_INDEX[id];
  if (!idx) return null;
  await init();
  await ensureChapter(idx.ch);
  let rec = null;
  if (db) rec = await idbGet('solutions', id);
  else if (chapterMem.has(idx.ch)) rec = chapterMem.get(idx.ch).SOLUTIONS[id] || null;
  if (!rec) return null;
  return { id, ch: idx.ch, entry: rec.entry, mode: rec.mode, reason: rec.reason || null, files: rec.files || {} };
}
